-- D1 read-budget: get_usage's period read scanned the whole workspace slice.
--
-- Measured 2026-10-02 via the D1 query API's meta.rows_read, on the largest
-- production workspace (2,469 UsageLog rows):
--
--   SELECT * FROM "UsageLog"
--    WHERE "workspaceId" = ? AND "createdAt" >= ?      -- "2026-10-01"
--    ORDER BY "createdAt" DESC
--
--     rows_read = 2,480
--
-- for a period containing TEN rows. The workspace's rows by month are
-- 27 Jul / 1,207 Aug / 1,225 Sep / 10 Oct, so 99.6% of the read was rows the
-- query then threw away.
--
-- Why, from EXPLAIN QUERY PLAN:
--
--   SEARCH UsageLog USING INDEX UsageLog_workspaceId_idx (workspaceId=?)
--   USE TEMP B-TREE FOR ORDER BY
--
-- No index leads with (workspaceId, createdAt), so SQLite can only seek the
-- workspaceId equality and then has to evaluate the createdAt range on every
-- one of the workspace's rows and sort them in a temp B-tree. The
-- UsageLog(workspaceId, kind, provider, createdAt) index from 0007 does not
-- help: createdAt is its LAST column, so it cannot serve either the range or
-- the ORDER BY.
--
-- Adding LIMIT 20 does NOT fix it — measured, still 2,480 rows read, because
-- the sort happens before the limit. Same failure shape as the CASE ORDER BY
-- that #103/#109 removed from get_usage's ledger read.
--
-- This index turns the read into a bounded range seek:
--
--   SEARCH UsageLog USING INDEX UsageLog_workspaceId_createdAt_idx
--          (workspaceId=? AND createdAt>?)
--
-- no temp B-tree, and rows_read falls to the size of the requested period.
--
-- Honest limit: with period "all" the aggregate still has to read every row,
-- because "total spend" cannot be computed without them. That one is a real
-- read, unlike the ledger SUM that SLA-326 removed — for it the fix would be
-- a daily rollup table, not an index.
--
-- Mirrors the @@index addition in prisma/schema.prisma (and
-- prisma/schema.sqlite.prisma, generated by src/scripts/sync-sqlite-schema.ts).
--
-- Apply with: wrangler d1 migrations apply slashloop --remote
CREATE INDEX IF NOT EXISTS "UsageLog_workspaceId_createdAt_idx"
  ON "UsageLog"("workspaceId", "createdAt");